#!/usr/bin/env python3
"""Turns the setup page assets into a C header.

The pages are plain HTML/CSS/JS files so they can be edited, diffed and linted
like any other web page, instead of hiding as C string literals with escaped
quotes. The pages pull the stylesheet and the scripts in with a single
directive:

    <!-- include: page.css -->

The generator replaces that line with the file content verbatim and writes the
result into src/web/pages.h, one `static const char` per page plus its length.
webserver.c includes that header and serves one document per page straight from
flash: no filesystem, no partition, nothing to mount at runtime, and no second
request for the CSS or the JavaScript.

The include is deliberately a plain text substitution, not a template engine:
included files are never re-parsed, so braces, comments and `</script>`-like
text in the assets cannot be interpreted or broken. It also means there are no
extra build dependencies next to the Python that PlatformIO already needs.

The header is generated and git-ignored. Called from two places:
- scripts/pio_generate_web.py before every PlatformIO build, so editing an
  asset is enough (PlatformIO only reconfigures CMake when its own files
  change).
- src/CMakeLists.txt at configure time, so a plain idf.py build works too.

usage: generate_web.py <directory holding the assets>
"""

import os
import re
import sys

# Header variable name -> page template. The stylesheet and the scripts are
# included by the templates, so each of these becomes one HTTP response.
ASSETS = [
    ("page_html", "page.html"),
    ("setup_html", "setup.html"),
]

HEADER = "pages.h"

# One include per line, one level deep. The name is restricted to a plain file
# name so a template cannot pull in a path outside the asset directory.
INCLUDE = re.compile(
    r"^[ \t]*<!--[ \t]*include:[ \t]*([A-Za-z0-9_.-]+)[ \t]*-->[ \t]*\r?\n?",
    re.MULTILINE,
)


def escape(data):
    """Escapes bytes for a C string literal.

    Everything printable stays readable; control characters and anything above
    ASCII becomes an octal escape, which - unlike \\x - is always three digits
    and therefore cannot swallow the next character.
    """
    out = []
    for byte in data:
        if byte == 0x0A:
            out.append("\\n")
        elif byte == 0x0D:
            out.append("\\r")
        elif byte == 0x09:
            out.append("\\t")
        elif byte == 0x22:
            out.append('\\"')
        elif byte == 0x5C:
            out.append("\\\\")
        elif 0x20 <= byte < 0x7F:
            out.append(chr(byte))
        else:
            out.append("\\%03o" % byte)
    return "".join(out)


def expand_includes(text, directory, origin):
    """Replaces every include directive with the verbatim file content.

    Included files are not expanded again, so an asset can never recurse or
    pull in another path. A missing file, a nested directive or a closing tag
    inside the asset fails the build instead of shipping a broken page.
    """

    def replace(match):
        name = match.group(1)
        path = os.path.join(directory, name)
        if not os.path.isfile(path):
            raise ValueError("%s: included file %s not found" % (origin, name))
        with open(path, "r", encoding="utf-8", newline="") as fp:
            content = fp.read()
        if name.endswith(".js") and "</script" in content.lower():
            raise ValueError("%s: %s contains </script>" % (origin, name))
        if name.endswith(".css") and "</style" in content.lower():
            raise ValueError("%s: %s contains </style>" % (origin, name))
        if not content.endswith("\n"):
            content += "\n"
        return content

    text = INCLUDE.sub(replace, text)
    if "<!-- include:" in text:
        raise ValueError("%s: unresolved or nested include directive" % origin)
    return text


def read_asset(directory, filename):
    """Returns the asset as bytes, with includes expanded for page templates."""
    with open(os.path.join(directory, filename), "r", encoding="utf-8",
              newline="") as fp:
        text = fp.read()
    if filename.endswith(".html"):
        text = expand_includes(text, directory, filename)
    return text.encode("utf-8")


def render(directory):
    lines = [
        "// Generated by scripts/generate_web.py from the files in this",
        "// directory - do not edit, do not commit.",
        "",
        "#ifndef PAGES_H",
        "#define PAGES_H",
    ]
    for name, filename in ASSETS:
        data = read_asset(directory, filename)
        lines.append("")
        lines.append("// " + filename)
        lines.append("static const char %s[] =" % name)
        # One literal per source line keeps the header readable in a diff and
        # avoids gigantic single-line strings.
        rows = data.split(b"\n")
        for index, row in enumerate(rows):
            text = escape(row)
            if index < len(rows) - 1:
                text += "\\n"
            lines.append('    "%s"' % text)
        lines.append(";")
        lines.append("static const unsigned %s_len = sizeof(%s) - 1;" % (name, name))
    lines.append("")
    lines.append("#endif // PAGES_H")
    lines.append("")
    return "\n".join(lines)


def generate(directory):
    """Writes the header if its content changed; returns True when it did."""
    target = os.path.join(directory, HEADER)
    content = render(directory)
    try:
        with open(target, "r", encoding="utf-8") as fp:
            if fp.read() == content:
                return False
    except OSError:
        pass
    with open(target, "w", encoding="utf-8") as fp:
        fp.write(content)
    print("generated " + target)
    return True


def main(argv):
    if len(argv) != 2:
        sys.stderr.write("usage: generate_web.py <asset directory>\n")
        return 1
    try:
        generate(argv[1])
    except (OSError, ValueError) as exc:
        sys.stderr.write("generate_web.py: %s\n" % exc)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
