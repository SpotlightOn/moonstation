#!/bin/sh
# Generates the self-signed HTTPS certificate of the setup web server into a
# C header. The build calls this when the header is missing (see
# src/CMakeLists.txt); the header is git-ignored, so a private key never
# lands in the repository.
#
# usage: generate_cert.sh <output header>

set -e

out="$1"
if [ -z "$out" ]; then
    echo "usage: generate_cert.sh <output header>" >&2
    exit 1
fi
if ! command -v openssl >/dev/null 2>&1; then
    echo "openssl is required to build the setup web server" >&2
    exit 1
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# Ten years, one name. The browser warns about the certificate, which is
# expected for a device that owns no domain; the traffic is still encrypted.
openssl req -x509 -newkey rsa:2048 -sha256 -days 3650 -nodes \
    -keyout "$tmp/key.pem" -out "$tmp/cert.pem" \
    -subj "/CN=moonstation.local" \
    -addext "subjectAltName=DNS:moonstation.local" >/dev/null 2>&1

# Writes one PEM file as a C string literal, one line per PEM line.
emit() {
    echo "static const char $2[] ="
    sed 's/.*/    "&\\n"/' "$1"
    echo ";"
}

{
    echo "// Generated by scripts/generate_cert.sh - do not edit, never commit."
    echo "// Self-signed certificate and private key of the setup web server."
    echo "// The browser warns about the certificate; that is expected on a"
    echo "// device without a domain, the connection itself is encrypted."
    echo ""
    emit "$tmp/cert.pem" server_cert_pem
    emit "$tmp/key.pem" server_key_pem
} > "$out"

echo "generated $out"
